"""Run every query in evals/questions.sql against evals/eval.sqlite and write the answers to evals/sql_answers.md."""

import re
import sqlite3
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main() -> None:
    text = (HERE / "questions.sql").read_text(encoding="utf-8")
    con = sqlite3.connect(HERE / "eval.sqlite")
    out = ["# SQL answers (generated by `python -m evals.run_sql` from `evals/questions.sql`)", ""]
    for block in re.split(r"\n(?=-- Q\d)", text):
        m = re.match(r"-- (Q\d+\. .+)", block)
        if not m:
            continue
        sql = "\n".join(line for line in block.splitlines() if not line.startswith("--"))
        cur = con.execute(sql)
        cols = [c[0] for c in cur.description]
        rows = cur.fetchall()
        out += [f"## {m.group(1)}", "", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        out += ["| " + " | ".join("" if v is None else str(v) for v in r) + " |" for r in rows]
        out.append("")
    (HERE / "sql_answers.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out[:40]))


if __name__ == "__main__":
    main()
